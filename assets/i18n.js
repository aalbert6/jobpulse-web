  function pick() {
    try {
      // ?lang=ca|es|en forces + persists a language — for testing and language-specific
      // invite links (e.g. /join-r9x2m/?lang=ca), overriding browser detection.
      var q = new URLSearchParams(location.search).get("lang");
      if (q) { q = q.slice(0, 2).toLowerCase(); if (DICT[q]) { localStorage.setItem("jp_lang", q); return q; } }
      var saved = localStorage.getItem("jp_lang");
      if (saved && DICT[saved]) return saved;
    } catch (e) {}
    var nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    return DICT[nav] ? nav : "en";
  }

  function apply(lang) {
    var d = DICT[lang] || DICT.en;
    document.documentElement.lang = lang;
    var t;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      t = d[el.getAttribute("data-i18n")];
      if (t != null) el.innerHTML = t;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      t = d[el.getAttribute("data-i18n-ph")];
      if (t != null) el.setAttribute("placeholder", t);
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      t = d[el.getAttribute("data-i18n-aria")];
      if (t != null) el.setAttribute("aria-label", t);
    });
    var titleKey = document.documentElement.getAttribute("data-i18n-title");
    if (titleKey && d[titleKey] != null) document.title = d[titleKey];
    // SEO: translated meta description / og:description / og:title follow the page language
    var descKey = document.documentElement.getAttribute("data-i18n-desc");
    if (descKey && d[descKey] != null) {
      ["meta[name=description]", "meta[property='og:description']", "meta[name='twitter:description']"].forEach(function (q) {
        var m = document.querySelector(q); if (m) m.setAttribute("content", d[descKey]);
      });
    }
    if (titleKey && d[titleKey] != null) {
      ["meta[property='og:title']", "meta[name='twitter:title']"].forEach(function (q) {
        var m = document.querySelector(q); if (m) m.setAttribute("content", d[titleKey]);
      });
    }
    try { localStorage.setItem("jp_lang", lang); } catch (e) {}
    CUR = lang;
    var sel = document.getElementById("lang-switch");
    if (sel) sel.value = lang;
    // Let JS-rendered pages (e.g. the dashboard) translate their dynamic strings + re-render.
    try { document.dispatchEvent(new CustomEvent("jp:lang", { detail: lang })); } catch (e) {}
  }

  // Public helpers for pages that build content in JS (i18n only auto-translates static
  // data-i18n elements present at apply() time).
  window.jpt = function (key) { var d = DICT[CUR] || DICT.en; return d[key] != null ? d[key] : key; };
  window.jpLang = function () { return CUR; };

  function mount() {
    var sel = document.getElementById("lang-switch");
    if (sel) {
      sel.setAttribute("aria-label", "Language");
      sel.innerHTML = LANGS.map(function (p) {
        return '<option value="' + p[0] + '">' + p[1] + "</option>";
      }).join("");
      sel.addEventListener("change", function () { apply(sel.value); });
    }
    apply(pick());
  }

  if (document.readyState !== "loading") mount();
  else document.addEventListener("DOMContentLoaded", mount);
